/**
 * scripts/generate-firebase-config.js
 *
 * Build-time generator for firebase-config.js.
 * Reads Firebase configuration from environment variables (e.g. Vercel Project Settings)
 * or local .env file, validates all required parameters, and outputs window.FIREBASE_CONFIG.
 *
 * Zero external dependencies. Safe error reporting (secrets redacted).
 */

const fs = require('fs');
const path = require('path');

const REQUIRED_CONFIG_KEYS = [
  'apiKey',
  'authDomain',
  'projectId',
  'storageBucket',
  'messagingSenderId',
  'appId'
];

const ENV_VAR_MAPPING = {
  apiKey: 'FIREBASE_API_KEY',
  authDomain: 'FIREBASE_AUTH_DOMAIN',
  projectId: 'FIREBASE_PROJECT_ID',
  storageBucket: 'FIREBASE_STORAGE_BUCKET',
  messagingSenderId: 'FIREBASE_MESSAGING_SENDER_ID',
  appId: 'FIREBASE_APP_ID'
};

const PLACEHOLDER_VALUES = [
  'YOUR_FIREBASE_API_KEY',
  'your-firebase-api-key',
  'YOUR_PROJECT_ID',
  'your-project-id',
  'YOUR_PROJECT_ID.firebaseapp.com',
  'your-project-id.firebaseapp.com',
  'YOUR_PROJECT_ID.firebasestorage.app',
  'your-project-id.firebasestorage.app',
  'YOUR_MESSAGING_SENDER_ID',
  'your-messaging-sender-id',
  'YOUR_APP_ID',
  'your-app-id'
];

/**
 * Minimal zero-dependency .env parser for local builds.
 */
function parseEnvFile(filePath) {
  if (!fs.existsSync(filePath)) return {};
  const content = fs.readFileSync(filePath, 'utf8');
  const env = {};
  for (const line of content.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eqIdx = trimmed.indexOf('=');
    if (eqIdx <= 0) continue;
    const key = trimmed.slice(0, eqIdx).trim();
    let val = trimmed.slice(eqIdx + 1).trim();
    if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
      val = val.slice(1, -1);
    }
    env[key] = val;
  }
  return env;
}

const VERIFIED_PRODUCTION_PROJECT_ID = 'temple-f4f7d';

/**
 * Validates configuration object.
 * Returns { valid: boolean, missing: string[], config: object }
 */
function validateConfig(rawConfig, allowDummy = false) {
  const missing = [];
  const config = {};

  for (const key of REQUIRED_CONFIG_KEYS) {
    const envVar = ENV_VAR_MAPPING[key];
    const val = rawConfig[key];

    if (!val || typeof val !== 'string' || val.trim().length === 0) {
      missing.push(`${envVar} (missing)`);
    } else if (!allowDummy && PLACEHOLDER_VALUES.includes(val.trim())) {
      missing.push(`${envVar} (contains placeholder)`);
    } else if (!allowDummy && key === 'projectId' && val.trim() !== VERIFIED_PRODUCTION_PROJECT_ID) {
      missing.push(`${envVar} (must match verified project "${VERIFIED_PRODUCTION_PROJECT_ID}", got "${val.trim()}")`);
    } else {
      config[key] = val.trim();
    }
  }

  return {
    valid: missing.length === 0,
    missing,
    config
  };
}

/**
 * Resolves configuration from environment variables and optional .env file.
 */
function resolveConfig(envSource = process.env, localEnvPath = path.resolve(__dirname, '../.env')) {
  let fileEnv = {};
  if (fs.existsSync(localEnvPath)) {
    try {
      fileEnv = parseEnvFile(localEnvPath);
    } catch (err) {
      console.warn('[Build Warning] Could not parse local .env file:', err.message);
    }
  }

  const rawConfig = {};
  for (const [cfgKey, envKey] of Object.entries(ENV_VAR_MAPPING)) {
    rawConfig[cfgKey] = envSource[envKey] || fileEnv[envKey] || '';
  }

  return rawConfig;
}

/**
 * Generates the firebase-config.js file content.
 */
function generateConfigContent(config) {
  return `// Auto-generated by scripts/generate-firebase-config.js during build
// Do NOT commit this file to version control.
window.FIREBASE_CONFIG = ${JSON.stringify(config, null, 2)};
`;
}

/**
 * Main build execution function.
 */
function generateFirebaseConfig(options = {}) {
  const envSource = options.envSource || process.env;
  const localEnvPath = options.localEnvPath || path.resolve(__dirname, '../.env');
  const outputPath = options.outputPath || path.resolve(__dirname, '../firebase-config.js');
  const allowDummy = options.allowDummy || false;

  const rawConfig = resolveConfig(envSource, localEnvPath);
  const validation = validateConfig(rawConfig, allowDummy);

  if (!validation.valid) {
    const errorMsg = `[Build Error] Firebase configuration validation failed.\nMissing or invalid environment variables:\n  - ${validation.missing.join('\n  - ')}\nAll secrets have been redacted from this error log.`;
    if (options.silentFail) {
      return { success: false, error: errorMsg, missing: validation.missing };
    }
    console.error(errorMsg);
    process.exit(1);
  }

  const content = generateConfigContent(validation.config);
  const outputDir = path.dirname(outputPath);
  if (!fs.existsSync(outputDir)) {
    fs.mkdirSync(outputDir, { recursive: true });
  }
  fs.writeFileSync(outputPath, content, 'utf8');

  console.log(`[Build] firebase-config.js generated successfully.`);
  console.log(`[Build] Target Project ID: ${validation.config.projectId}`);
  console.log(`[Build] Auth Domain: ${validation.config.authDomain}`);
  console.log(`[Build] Output file: ${path.relative(process.cwd(), outputPath)}`);

  return { success: true, config: validation.config };
}

if (require.main === module) {
  generateFirebaseConfig();
}

module.exports = {
  REQUIRED_CONFIG_KEYS,
  ENV_VAR_MAPPING,
  PLACEHOLDER_VALUES,
  parseEnvFile,
  validateConfig,
  resolveConfig,
  generateConfigContent,
  generateFirebaseConfig
};
