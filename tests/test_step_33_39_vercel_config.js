// Route simulation function based on vercel.json rewrites
function simulateVercelRoute(requestPath) {
  for (const rule of vercelConfig.rewrites) {
    const src = rule.source;
    // Test exact slash match
    if (src === '/' && requestPath === '/') {
      return { destination: rule.destination, status: rule.statusCode || 200, rule: src };
    }
    // Test regex patterns
    try {
      const regex = new RegExp(`^${src}$`);
      if (regex.test(requestPath)) {
        return { destination: rule.destination, status: rule.statusCode || 200, rule: src };
      }
    } catch (e) {
      // If path-to-regexp pattern like /backups/:path*
      if (src.includes(':path*')) {
        const prefix = src.replace(':path*', '');
        if (requestPath.startsWith(prefix) || requestPath === prefix.replace(/\/$/, '')) {
          return { destination: rule.destination, status: rule.statusCode || 200, rule: src };
        }
      }
    }
  }
  // Default filesystem pass-through
  return { destination: requestPath, status: 200, rule: 'filesystem' };
}

